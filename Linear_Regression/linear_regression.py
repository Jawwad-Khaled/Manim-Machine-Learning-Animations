        text2 = Tex('Solution for the case with p predictors').shift(UP*1.25)
        text3 = Tex('Gradient descent')
        text4 = Tex('Categorical variables').shift(DOWN*1.25)
        text5 = Tex('Implementation using numpy').shift(DOWN*2.5)
        text6 = Tex('Finding partial derivatives').shift(UP*1)
        text7 = Tex('Finding critical points for multivariable functions')
        text8 = Tex('Some linear algebra').shift(DOWN*1)
