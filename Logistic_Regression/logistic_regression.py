class Gradient_Descent_Contour_Plot_Normal(Scene):
    def construct(self):
        number_plane = NumberPlane(x_range=[-5, 5], y_range=[-5, 5])
        origin = Dot(number_plane.c2p(0, 0))
        graph1 = ImplicitFunction(lambda x, y: x**2 + y**2 - 1, x_range=[-5, 5], y_range=[-5, 5])
        graph2 = ImplicitFunction(lambda x, y: x**2 + y**2 - 4, x_range=[-5, 5], y_range=[-5, 5])
        graph3 = ImplicitFunction(lambda x, y: x**2 + y**2 - 9, x_range=[-5, 5], y_range=[-5, 5])
        point_on_circle = np.array([3*np.cos(PI/4), 3*np.sin(PI/4), 0])
        direction = np.array([2*point_on_circle[0], 2*point_on_circle[1], 0])
        direction = direction / np.linalg.norm(direction)
        vector = Arrow(start=point_on_circle, end=point_on_circle+direction, buff=0, color=YELLOW)
        point = Dot(vector.get_start(), color=BLUE)

        self.play(Create(origin), Create(number_plane), Create(graph1), Create(graph2), Create(graph3))
        self.wait()
        self.add(vector, point)
        self.wait()
        for i in range(0, 100):
            self.play(point.animate.shift(-0.1*direction), vector.animate.shift(-0.1*direction), run_time=0.1)
            direction = vector.get_start()
        self.wait()

